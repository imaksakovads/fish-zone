#!/usr/bin/env bash
# Волна 2: 6 статей. Определяет файл как последний созданный (надёжно при транслите)
cd /Users/igor/project/fish-zone
unset PYTHONPATH
export PY=".venv/bin/python"

gen() {
  local title="$1" cat="$2" tags="$3"
  echo "═══ Генерация: $title ═══"
  local before=$(ls -t content/*.md | head -1)
  $PY build.py --generate "$title" --category "$cat" --tags "$tags" 2>&1 | grep -E "Гуманизатор ответил|Создана" | tail -2
  local f=$(ls -t content/*.md | head -1)
  if [ "$f" = "$before" ]; then echo "  (файл не изменился)"; fi
  echo "  → $f, $(wc -c < "$f") байт, директивы: $(grep -cE ':::' "$f")"
  bash run_critic.sh "$f" 2>&1 | grep -E "Verdict" | head -1
  echo ""
}

gen "Как выбрать воблер для спиннинга: полный гид" "lure" "воблер, выбор воблера, спиннинг, минноу, крэнк"
gen "Как выбрать блесну для спиннинга: колебалки и вертушки" "lure" "блесна, колебалка, вертушка, выбор блесны, спиннинг"
gen "Твичинг на спиннинге: техника ловли воблером" "technique" "твичинг, техника ловли, воблер, рывковая проводка"
gen "Троллинг на спиннинге: снасти и техника с лодки" "technique" "троллинг, ловля с лодки, воблер, снасти"
gen "Отводной поводок: монтаж и техника ловли" "rig" "отводной поводок, монтаж, оснастка, техника"
gen "Дроп-шот: оснастка и техника ловли" "rig" "дроп-шот, оснастка, техника, монтаж, спиннинг"

echo "═══ ВОЛНА 2 ГОТОВА ═══"
