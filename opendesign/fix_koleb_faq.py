#!/usr/bin/env python3
"""Koleblyuschiesya: заменяет чужой FAQ на релевантный."""
import re
p = "/Users/igor/project/fish-zone/content/koleblyuschiesya-blyosny-vybrat-lovit.md"
txt = open(p, encoding="utf-8").read()

new_faq = """## FAQ

:::faq **На какую рыбу ловить колеблющуюся блесну?**
На щуку, судака и окуня. Колебалка — универсальная приманка для хищников, которые держатся у дна. Для щуки — крупные колебалки 10-25 г, для судака — узкотелые 15-30 г, для окуня — мелкие 3-7 г.
:::

:::faq **Какая проводка у колебалки?**
Медленная равномерная с паузами. Блесна должна идти в 10-15 см от дна, слегка касаясь его и поднимая муть. Паузы 1-2 секунды на каждые 3-5 оборотов. Это провоцирует хищника на хватку.
:::

:::faq **Чем колебалка отличается от вертушки?**
Колебалка колеблется из стороны в сторону при равномерной проводке и работает у дна. Вертушка вращается вокруг оси и лучше ловит в верхних слоях и траве. Колебалка эффективнее на глубине и течении, вертушка — на мелководье.
:::

:::faq **Когда лучше ловить на колебалку?**
Весной и осенью, когда хищник активен и держится у дна. Летом колебалка работает хуже (рыба уходит в траву и на глубину), а зимой почти не используется. Лучшее время — утро и вечер.
:::"""

# Заменим всё от "## FAQ" до конца
idx = txt.find("## FAQ")
if idx != -1:
    head = txt[:idx].rstrip() + "\n"
    open(p, "w", encoding="utf-8").write(head + "\n" + new_faq + "\n")
    print("Koleblyuschiesya: FAQ заменён")
