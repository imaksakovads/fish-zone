#!/usr/bin/env python3
"""Drop-shot: подразделы сценариев (Мелководье/Глубина/Заросли) -> H4."""
import re
p = "/Users/igor/project/fish-zone/content/drop-shot-osnastka-tehnika-lovli.md"
txt = open(p, encoding="utf-8").read()

# Внутри "Практические сценарии" подразделы Мелководье/Глубина/Заросли должны быть ####
# Найдём раздел и поменяем ### -> #### для этих заголовков (только после "Практические сценарии")
# Но осторожно: Мелководье может встречаться и как самостоятельный раздел.
# В drop-shot структура: ### Практические сценарии, затем ### Мелководье/Глубина/Заросли.
# Превратим Мелководье/Глубина/Заросли в #### (подразделы).

# Позиция "Практические сценарии"
idx = txt.find("### Практические сценарии")
# Найдём все ### после неё до следующего ### "Таблица"
seg = txt[idx:]
for sub in ["### Мелководье", "### Глубина", "### Заросли"]:
    seg = seg.replace(sub, "#### " + sub[4:])
# Заменяем в исходнике
txt = txt[:idx] + seg
open(p, "w", encoding="utf-8").write(txt)
print("Drop-shot: подразделы сценариев -> H4")
for m in re.finditer(r"^(#{1,4}) (.+)$", txt, re.M):
    print(f"  {m.group(1)} {m.group(2)}")
