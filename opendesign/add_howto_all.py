def main():
    content_dir = "/Users/igor/project/fish-zone/content"
    for f, (anchor, steps) in HOWTOS.items():
        path = os.path.join(content_dir, f)
        if not os.path.exists(path):
            print(f"  ✗ {f}: не найден")
            continue
        txt = open(path, encoding="utf-8").read()
        if ":::howto" in txt:
            print(f"  - {f}: уже есть howto, пропуск")
            continue
        # Формируем howto-блок
        howto = "\n".join(f":::howto **Шаг {i+1}: {steps[i][:40]}...**\n{steps[i]}\n:::\n" for i in range(len(steps)))
        # Якорь вставки
        if anchor:
            idx = txt.find(anchor)
            if idx == -1:
                print(f"  ✗ {f}: якорь '{anchor}' не найден")
                continue
            # Вставить после первого абзаца раздела
            end = txt.find("\n\n", idx)
            if end == -1:
                end = len(txt)
            txt = txt[:end] + "\n\n" + howto + txt[end:]
        else:
            # Нет раздела техники — вставить перед FAQ
            faq = txt.find("## FAQ")
            if faq == -1:
                faq = len(txt)
            txt = txt[:faq] + howto + "\n" + txt[faq:]
        open(path, "w", encoding="utf-8").write(txt)
        print(f"  ✓ {f}: howto добавлен")

if __name__ == "__main__":
    main()
