#!/usr/bin/env python3
"""Tviching: заменяет чужой FAQ на релевантный."""
import re
p = "/Users/igor/project/fish-zone/content/tviching-spinninge-tehnika-lovli-voblerom.md"
txt = open(p, encoding="utf-8").read()

new_faq = """## FAQ

:::faq **Что такое твичинг?**
Это рывковая проводка воблеров, при которой приманка идёт резкими скачками с паузами. Рывок кончиком удилища, подмотка слабины, пауза — цикл повторяется. Хищник атакует чаще всего в момент паузы, когда воблер замирает.
:::

:::faq **Какие воблеры нужны для твичинга?**
Лучше всего — минноу с узким телом и активной игрой. Длина 7-11 см для щуки, 5-7 см для окуня. Крэнки с собственной игрой проще для новичка. Глубина выбирается по горизонту ловли.
:::

:::faq **Какой ритм твичинга?**
Короткий рывок 10-20 см, подмотка слабины, пауза 2-5 секунд. Для окуня ритм быстрее, для щуки паузы длиннее. Меняйте амплитуду и паузу, пока не найдёте тот ритм, на который рыба реагирует сегодня.
:::

:::faq **Когда ловить твичингом?**
Весна и осень — лучшее время, когда хищник активен. Летом твичинг работает по окуню и щуке у травы, в пасмурные дни. Зимой — редко. Работает в толще воды и у дна с глубинными воблерами.
:::"""

idx = txt.find("## FAQ")
if idx != -1:
    head = txt[:idx].rstrip() + "\n"
    open(p, "w", encoding="utf-8").write(head + "\n" + new_faq + "\n")
    print("Tviching: FAQ заменён")
