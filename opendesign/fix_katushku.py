#!/usr/bin/env python3
"""Katushku: обрезает чужой блок про поводок после 'Итоговая рекомендация', добавляет FAQ про катушку."""
p = "/Users/igor/project/fish-zone/content/vybrat-katushku-spinninga-polnyy-gid.md"
txt = open(p, encoding="utf-8").read()

# Найдём раздел "Итоговая рекомендация" и его конец (до "Откуда взялась длина")
itog = txt.find("## Итоговая рекомендация")
chuzh = txt.find("## Откуда взялась длина в 20 см")
if itog != -1 and chuzh != -1 and itog < chuzh:
    # Обрезаем до конца раздела "Итоговая рекомендация" (до начала чужого)
    txt = txt[:chuzh].rstrip() + "\n"
    print("katushku: чужой блок про поводок удалён")

    # Добавляем релевантный FAQ про катушку
    faq = """\n## FAQ\n\n:::faq **Какой размер катушки выбрать для спиннинга?**\nУниверсальный размер — 2500 по классификации Шимано. Для лёгкого джига и окуня хватит 1000-2000, для тяжёлого джига и крупной щуки — 3000-4000. 2500 закрывает большинство задач.\n:::\n\n:::faq **Передний или задний фрикцион?**\nПередний фрикцион лучше для спиннинга. Он быстрее настраивается и плавнее работает под нагрузкой. Задний удобнее, но менее точен. Для джига и твичинга берите передний.\n:::\n\n:::faq **Сколько подшипников нужно катушке?**\nДостаточно 5-7 качественных подшипников. Больше — маркетинг. Важнее материал и качество сборки, чем количество подшипников. Хорошие японские подшипники служат годами.\n:::\n\n:::faq **Передаточное число — какое выбрать?**\nДля классического джига — 5.2:1, для твичинга и быстрых проводок — 6.2:1. Универсальный вариант — 5.2-6.2. Высокое число (7+) нужно только для специальных техник.\n:::\n"""
    txt = txt.rstrip() + "\n" + faq
    open(p, "w", encoding="utf-8").write(txt)
    print("katushku: FAQ про катушку добавлен")
else:
    print("katushku: маркеры не найдены (itog={}, chuzh={})".format(itog, chuzh))
