#!/usr/bin/env python3
"""Koleblyuschiesya: заменяет чужие howto про спиннинг на релевантные."""
import re
p = "/Users/igor/project/fish-zone/content/koleblyuschiesya-blyosny-vybrat-lovit.md"
txt = open(p, encoding="utf-8").read()

new_howto = """:::howto **Шаг 1: Заброс и касание дна**
Сделайте заброс и дождитесь, пока колебалка ляжет на дно. Сразу после касания выберите слабину шнура — важно чувствовать дно через бланк. Глубина касания зависит от веса блесны и силы течения.
:::

:::howto **Шаг 2: Равномерная проводка с паузами**
Начните медленную равномерную подмотку. Через каждые 3-5 оборотов делайте паузу на 1-2 секунды, давая блесне опуститься к дну. Во время паузы колебалка играет на падении — это и провоцирует хищника.
:::

:::howto **Шаг 3: Контроль горизонта**
Следите, чтобы колебалка шла в 10-15 см от дна. Если блесна выходит наверх — добавьте вес или замедлите проводку. Если цепляет дно слишком часто — ускорьтесь. Чирканье по дну с лёгкой мутью — то, что нужно.
:::

:::howto **Шаг 4: Подсечка и вываживание**
Поклёвка колебалки — резкий удар или «тупой» тычок. Подсекайте коротко и резко. Вываживайте, держа удилище под углом 45°, не давая рыбе уйти в коряги. Не ослабляйте натяжение шнура.
:::"""

# Найдём и заменим блок howto (от первого :::howto до перед ## FAQ)
m = re.search(r"(^:::howto.*?)(?=^## FAQ)", txt, re.S|re.M)
if m:
    txt = txt[:m.start()] + new_howto + "\n" + txt[m.end():]
    open(p, "w", encoding="utf-8").write(txt)
    print("Koleblyuschiesya: howto заменены")
else:
    print("howto блок не найден")
