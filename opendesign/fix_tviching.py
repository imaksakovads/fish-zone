#!/usr/bin/env python3
"""Tviching: заменяет чужие callout/howto про спиннинг на релевантные твичингу."""
import re
p = "/Users/igor/project/fish-zone/content/tviching-spinninge-tehnika-lovli-voblerom.md"
txt = open(p, encoding="utf-8").read()

new_calls = {
    "summary": ":::summary\n**Вывод за 30 секунд.** Твичинг — это рывковая проводка воблеров-минноу, при которой приманка идёт резкими скачками с паузами. Хищник атакует чаще всего в момент паузы, когда воблер замирает и слегка всплывает. Освойте короткий рывок кончиком удилища + подмотку слабины + паузу.\n:::",
    "experience": ":::experience\n**Опыт автора.** Я начинал с равномерной проводки и считал твичинг слишком сложным. Пока не понял главное: твичинг — это про паузы. Резкий рывок, короткая пауза, снова рывок. Щука и окунь берут именно в момент зависания воблера. Освоив ритм, я стал стабильно брать рыбу, которую раньше упускал.\n:::",
    "warning": ":::warning\n**Частая ошибка.** Делать твичинг слишком размашисто и часто, без пауз. Воблер должен идти резкими короткими рывками с выраженными паузами 2-5 секунд. Если крутить непрерывно, приманка не успевает замереть, и хищник не решается на хватку. Ритм важнее силы рывка.\n:::",
    "myth": ":::myth\n**Миф и правда.** Миф: твичинг работает только по щуке. Правда: твичинг отлично ловит окуня, судака, жереха и голавля. Для каждого хищника свой ритм и размер воблера. Окунь — мелкие минноу с быстрым ритмом, щука — крупные с длинными паузами, судак — глубинными.\n:::",
    "secret": ":::secret\n**Секрет.** Амплитуда рывка — 10-20 см, не больше. Резкий короткий рывок кончиком удилища, затем подмотка слабины и пауза. Во время паузы воблер слегка всплывает и дрожит — это и провоцирует хищника. Меняйте ритм, пока не найдёте тот, на который рыба реагирует сегодня.\n:::",
    "tip": ":::tip\n**Совет.** Для твичинга выбирайте воблеры-минноу с узким телом и активной игрой. Классика — минноу 7-9 см с быстрым строем удилища. Твичинг воблеров с собственной игрой (крэнков) проще для новичка — они работают даже на равномерной проводке.\n:::",
}

new_howto = """:::howto **Шаг 1: Заброс**
Сделайте заброс в перспективную точку — у травы, коряг, бровки. Дождитесь, пока воблер достигнет рабочего горизонта. Выберите слабину шнура до лёгкого натяжения.
:::

:::howto **Шаг 2: Рывок**
Резко, но коротко дёрните кончиком удилища в сторону — на 10-20 см. Воблер сделает скачок вперёд. Не делайте размашистых движений, важна резкость и амплитуда.
:::

:::howto **Шаг 3: Подмотка и пауза**
Сразу после рывка подмотайте слабину шнура и сделайте паузу 2-5 секунд. Во время паузы воблер замирает и слегка всплывает. Именно в этот момент происходит большинство поклёвок.
:::

:::howto **Шаг 4: Повтор и подсечка**
Повторяйте цикл «рывок — подмотка — пауза» до берега. При поклёвке (удар, натяжение) делайте резкую короткую подсечку и вываживайте, не давая рыбе уйти в коряги.
:::"""

# Замена callout с конца
blocks = list(re.finditer(r"^:::(summary|experience|warning|myth|secret|tip)\n.*?^:::", txt, re.S|re.M))
print("callout-блоков:", len(blocks))
repl = {}
for i, m in enumerate(blocks):
    if i < 6:
        typ = ["summary","experience","warning","myth","secret","tip"][i]
        repl[m.start()] = (m.end(), new_calls[typ])
for start in sorted(repl.keys(), reverse=True):
    end, r = repl[start]
    txt = txt[:start] + r + txt[end:]

# Замена howto
m = re.search(r"(^:::howto.*?)(?=^## FAQ)", txt, re.S|re.M)
if m:
    txt = txt[:m.start()] + new_howto + "\n" + txt[m.end():]

open(p, "w", encoding="utf-8").write(txt)
print("Tviching: чужие блоки заменены")
