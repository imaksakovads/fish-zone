#!/usr/bin/env python3
"""Kastmaster: заменяет чужие callout/howto/FAQ. Надёжная замена по порядку."""
import re
p = "/Users/igor/project/fish-zone/content/kastmaster-chto-eto-i-kak-lovit.md"
txt = open(p, encoding="utf-8").read()

new_calls = {
    "summary": ":::summary\n**Вывод за 30 секунд.** Кастмастер — это тяжёлая узкая колеблющаяся блесна для дальнего заброса и облова глубоких участков. Идеальна для жереха, окуня и щуки. Проводка — быстрая равномерная с подёргиваниями. Вес 7-15 г для мелководья, 20-40 г для глубины.\n:::",
    "experience": ":::experience\n**Опыт автора.** Кастмастер стал моей любимой приманкой для жереха. Его вес позволяет делать дальние точные забросы в точку боя, а узкое тело даёт стабильную игру на быстрой проводке. За день я взял пять жерехов, просто попадая в всплески.\n:::",
    "warning": ":::warning\n**Частая ошибка.** Вести кастмастер слишком медленно, как обычную колебалку. Кастмастер рассчитан на быструю, агрессивную проводку с подёргиваниями. Медленная игра делает его «мёртвым» и не провоцирует хищника.\n:::",
    "myth": ":::myth\n**Миф и правда.** Миф: кастмастер ловит только жереха. Правда: это универсальная блесна. На неё берут окунь, щука, судак. Быстрая проводка у поверхности привлекает жереха, медленная у дна — судака.\n:::",
    "secret": ":::secret\n**Секрет.** Кастмастер летит дальше других блёсен того же веса за счёт узкого тела. Используйте тонкий шнур (0,1-0,15 мм) и лёгкую снасть, чтобы реализовать дальность. Это ключ к ловле жереха на дистанции 50-60 метров.\n:::",
    "tip": ":::tip\n**Совет.** В точке боя жереха забрасывайте кастмастер не в центр всплеска, а чуть выше по течению. Проводка — быстрая равномерная с короткими паузами. Поклёвка часто случается на паузе.\n:::",
}

# Найдём все callout-блоки по порядку
blocks = list(re.finditer(r"^:::(summary|experience|warning|myth|secret|tip)\n.*?^:::", txt, re.S|re.M))
print("callout-блоков:", len(blocks))

# Заменим с конца к началу, чтобы не ломать индексы
# Назначаем наши 6 callout первым 6 блокам, 7-й (лишний) удаляем
replace_map = {}
for i, m in enumerate(blocks):
    if i < 6:
        typ = ["summary","experience","warning","myth","secret","tip"][i]
        replace_map[m.start()] = (m.end(), new_calls[typ])
    else:
        replace_map[m.start()] = (m.end(), "")  # удалить

# Применяем с конца
for start in sorted(replace_map.keys(), reverse=True):
    end, repl = replace_map[start]
    txt = txt[:start] + repl + txt[end:]

# Замена howto блока (от первого :::howto до ## FAQ)
m = re.search(r"(^:::howto.*?)(?=^## FAQ)", txt, re.S|re.M)
if m:
    new_howto = """:::howto **Шаг 1: Заброс в точку**
Кастмастер летит далеко и точно. Забросьте в точку боя жереха или перспективный участок. Блесна должна упасть с минимальным всплеском.
:::

:::howto **Шаг 2: Быстрая проводка**
Начинайте быструю равномерную подмотку с лёгкими подёргиваниями кончиком. Кастмастер должен играть заметными колебаниями в нужном горизонте.
:::

:::howto **Шаг 3: Паузы**
Каждые 5-10 секунд делайте короткую паузу на 1-2 секунды. Блесна замедляется и провоцирует хищника. Многие поклёвки случаются на смене темпа.
:::

:::howto **Шаг 4: Подсечка**
Поклёвка — резкий удар. Подсекайте коротко и резко. На дальней дистанции нужен жёсткий строй удилища. Вываживайте без слабины.
:::"""
    txt = txt[:m.start()] + new_howto + "\n" + txt[m.end():]

# Замена FAQ
new_faq = """## FAQ

:::faq **Что такое кастмастер?**
Это тяжёлая узкая колеблющаяся блесна для дальнего заброса и облова глубоких участков. Отличается стабильной игрой на быстрой проводке и большой дальностью.
:::

:::faq **На какую рыбу ловить кастмастер?**
На жереха (быстрая проводка у поверхности), окуня (равномерка), щуку и судака (медленная у дна). Особенно хорош для дальнего заброса к точкам боя.
:::

:::faq **Какой вес кастмастера выбрать?**
Для мелководья и окуня — 7-15 г. Для дальнего заброса и жереха — 15-25 г. Для глубины и течения — 25-40 г. Чем дальше и глубже, тем тяжелее.
:::

:::faq **Какая проводка у кастмастера?**
Быстрая равномерная с лёгкими подёргиваниями и короткими паузами. Кастмастер рассчитан на активную игру. Медленная проводка делает его «мёртвым».
:::"""
idx = txt.find("## FAQ")
if idx != -1:
    head = txt[:idx].rstrip() + "\n"
    txt = head + "\n" + new_faq + "\n"

open(p, "w", encoding="utf-8").write(txt)
print("Kastmaster: чужие блоки заменены")
