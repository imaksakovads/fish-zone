#!/usr/bin/env python3
"""Постобработка сконвертированной статьи судака: чистка артефактов, добавление таблицы/картинок."""
import re

F = "/Users/igor/project/fish-zone/content/lovit-sudaka-spinning-tehnika-snasti.md"
t = open(F, encoding="utf-8").read()

# 1. Убрать строки-секции (01`, 02`...) — лишний TOC-дамп
t = re.sub(r"^\d{2}`\s*$", "", t, flags=re.M)

# 2. Убрать сырые Q1`..Q4` (они уже есть в ## FAQ)
t = re.sub(r"^Q\d`\s*$", "", t, flags=re.M)

# 3. callout: убрать артефакт "**.** " в начале содержимого
t = t.replace(":::summary\n**.** ", ":::summary\n")
t = t.replace(":::experience\n**.** ", ":::experience\n")
t = t.replace(":::warning\n**.** ", ":::warning\n")
t = t.replace(":::myth\n**.** ", ":::myth\n")
t = t.replace(":::secret\n**.** ", ":::secret\n")
t = t.replace(":::tip\n**.** ", ":::tip\n")

# 4. callout "Цвет приманки" — восстановить пропущенное слово
t = t.replace(":::tip\n** важен.**", ":::tip\n**Цвет приманки** важен.")

# 5. FAQ: убрать дубли (сырые Q-блоки уже удалены в шаге 2; проверить нет ли задвоения текста)
# Убрать повторяющийся кусок между удалёнными QN и ## FAQ, если остался
# (текст ответов уже в ## FAQ, сырые удалены)

# 6. Сводная таблица: добавить таблицу после "## Сводная таблица по условиям"
TABLE = """| Условия | Снасть | Приманка | Тактика |
| --- | --- | --- | --- |
| Весна, берег, глубина 2–4 м | Спиннинг 2,4 м, тест 10–30, шнур 0,12 | Силикон 3–4″, джиг 14–18 г | Классический джиг с длинными паузами |
| Лето, ночь, глубина 4–8 м | Спиннинг 2,1 м, тест 7–21, шнур 0,10 | Воблер-минноу, глубина 3–5 м | Медленный твичинг, паузы до 5 сек |
| Осень, день, глубина 5–10 м | Спиннинг 2,4 м, тест 15–40, шнур 0,14 | Силикон 4–5″, джиг 25–35 г | Ступенька с волочением по дну |
| Коряжник | Спиннинг 2,4 м, тест 10–30, шнур 0,12 | Незацепляйка, офсетный крючок | Медленная проводка с подергиваниями |
| Глубокий свал | Спиннинг 2,6 м, тест 20–50, шнур 0,14 | Тяжелая колебалка 25–40 г | Равномерная проводка |
"""
t = t.replace("## Сводная таблица по условиям\n\n", "## Сводная таблица по условиям\n\n" + TABLE + "\n")

# 7. Добавить недостающие картинки (приманки, джиг) если нет
if "primanki" not in t:
    t = t.replace("**Силиконовые приманки** — это база.",
                  "![Приманки для судака: джиг-головки, силикон и колебалки](/images/lovit-sudaka-spinning-tehnika-snasti-primanki.webp)\n\n**Силиконовые приманки** — это база.")
if "dzhig" not in t:
    t = t.replace("Стандартная джиговая проводка — это не просто",
                  "![Ступенчатая джиговая проводка на глубине](/images/lovit-sudaka-spinning-tehnika-snasti-dzhig.webp)\n\nСтандартная джиговая проводка — это не просто")

# Убрать лишние пустые строки
t = re.sub(r"\n{3,}", "\n\n", t)

open(F, "w", encoding="utf-8").write(t)
print("Постобработка готова")
print("Размер:", len(t))
print("Картинки:", t.count("!["))
print("Таблица есть:", "Сводная таблица" in t and "| Условия |" in t)
print("Осталось мусора:", len(re.findall(r"^\d{2}`|^Q\d`", t, re.M)))
