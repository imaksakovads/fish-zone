"""Povodok: заменяет чужие callout/howto/FAQ про спиннинг на релевантные поводку."""
import re
p = "/Users/igor/project/fish-zone/content/vybrat-privyazat-povodok-spinninga.md"
txt = open(p, encoding="utf-8").read()

new_calls = {
    "summary": ":::summary\n**Вывод за 30 секунд.** Поводок обязателен, если есть риск щуки — она перекусывает плетёнку. Для щуки — стальной поводок 15-25 см или толстый флюорокарбон 0,5 мм. Для судака и окуня — флюорокарбон 0,25-0,35 мм. Длина поводка 15-30 см, в коряжнике — до 50 см.\n:::",
    "experience": ":::experience\n**Опыт автора.** Я потерял десятки приманок, пока не поставил стальной поводок на щуку. Одна атака — и воблер за 500 рублей остался в пасти хищника. Теперь стальной поводок 20 см — обязательный элемент на любой рыбалке, где есть шанс щуки. Экономия приманок окупила поводки многократно.\n:::",
    "warning": ":::warning\n**Частая ошибка.** Использовать слишком короткий поводок или обходиться без него. Если поводок короче 15 см, щука при хватке может перекусить основную леску над ним. А без поводка на щучьей рыбалке вы рискуете потерять приманку при первой же атаке. Длина 20-25 см — минимум.\n:::",
    "myth": ":::myth\n**Миф и правда.** Миф: толстый поводок отпугивает рыбу, поэтому лучше без него. Правда: поводок почти не влияет на клёв, особенно в мутной воде и на течении. А вот потеря приманки из-за щуки — реальная проблема. Современные тонкие поводки из титана и кевлара малозаметны и надёжны.\n:::",
    "secret": ":::secret\n**Секрет.** Для ловли на джиг поводок из флюорокарбона лучше стального — он менее заметен и не отпугивает судака и окуня. Для щуки в коряжнике — стальной или титановый. Тонкий поводок из кевлара хорош для судака, но слаб против щуки — используйте его с металлическим.\n:::",
    "tip": ":::tip\n**Совет.** Всегда смачивайте узел при вязании поводка. Сухой флюорокарбон при затяжке пережигается и теряет до половины прочности. Используйте узлы «паломар» или «клинч» для плетёнки, «морис» для флюорокарбона. Плавное затягивание без рывков.\n:::",
}

new_howto = """:::howto **Шаг 1: Выберите материал**
Для щуки — стальной или титановый поводок (держит зубы). Для судака и окуня — флюорокарбон 0,25-0,35 мм (менее заметен). В коряжнике — стальной с флюорокарбоновой вставкой или титановый.
:::

:::howto **Шаг 2: Определите длину**
Минимальная для щуки — 15 см, рабочая — 20-25 см. Для отводного поводка — до 50 см. В коряжнике — не менее 40 см, чтобы щука не перекусила шнур при рывке.
:::

:::howto **Шаг 3: Привяжите узел**
Смочите узел и затягивайте плавно. Для плетёнки — паломар или клинч, для флюорокарбона — морис. Крепите поводок через вертлюжок с застёжкой, чтобы не перекручивался шнур.
:::

:::howto **Шаг 4: Проверьте перед забросом**
Проверьте поводок на износ и затяжку узлов перед каждой рыбалкой. Повреждённый поводок замените. Потеря приманки из-за слабого поводка обойдётся дороже нового поводка.
:::"""

new_faq = """## FAQ

:::faq **Нужен ли поводок при ловле на спиннинг?**
Обязательно, если есть риск щуки — она перекусывает плетёнку. Для щуки — стальной или титановый поводок. Для судака и окуня можно флюорокарбон, если нет щуки в водоёме.
:::

:::faq **Какой поводок лучше для щуки?**
Стальной или титановый. Сталь жёсткая и надёжная, титан легче и гибче. Длина 15-25 см. Стальной поводок из струны идеален для ловли в траве и корягах.
:::

:::faq **Какой поводок для судака и окуня?**
Флюорокарбон 0,25-0,35 мм. Он почти невидим в воде и не отпугивает рыбу. Для судака длина 25-30 см, для окуня достаточно 10-15 см. Если рядом есть щука — ставьте стальной.
:::

:::faq **Какой длины делать поводок?**
Для щуки — минимум 15-20 см, чтобы она не перекусила основную леску. Для отводного — до 50 см. В коряжнике — не менее 40 см. Длина подбирается под приманку и условия.
:::"""

# Замена callout с конца
blocks = list(re.finditer(r"^:::(summary|experience|warning|myth|secret|tip)\n.*?^:::", txt, re.S|re.M))
print("callout-блоков:", len(blocks))
repl = {}
for i, m in enumerate(blocks):
    if i < 6:
        typ = ["summary","experience","warning","myth","secret","tip"][i]
        repl[m.start()] = (m.end(), new_calls[typ])
for start in sorted(repl.keys(), reverse=True):
    end, r = repl[start]
    txt = txt[:start] + r + txt[end:]

# Замена howto
m = re.search(r"(^:::howto.*?)(?=^## FAQ)", txt, re.S|re.M)
if m:
    txt = txt[:m.start()] + new_howto + "\n" + txt[m.end():]

# Замена FAQ
idx = txt.find("## FAQ")
if idx != -1:
    head = txt[:idx].rstrip() + "\n"
    txt = head + "\n" + new_faq + "\n"

open(p, "w", encoding="utf-8").write(txt)
print("Povodok: чужие блоки заменены")
