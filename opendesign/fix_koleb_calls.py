#!/usr/bin/env python3
"""Koleblyuschiesya: заменяет чужие callout про спиннинг на релевантные блёснам."""
import re
p = "/Users/igor/project/fish-zone/content/koleblyuschiesya-blyosny-vybrat-lovit.md"
txt = open(p, encoding="utf-8").read()

# Релевантные callout для колеблющихся блёсен
new_calls = {
    "summary": """:::summary
**Вывод за 30 секунд.** Колеблющаяся блесна — это универсальная приманка для щуки, судака и окуня. Для щуки берите колебалки 10-25 грамм с широкой амплитудой, для судака — 15-30 грамм узкотелые, для окуня — 3-7 грамм. Лучшие периоды — весна и осень, когда хищник активен у дна.
:::""",
    "experience": """:::experience
**Опыт автора.** Я долго считал колебалку «скучной» приманкой, пока не понял её силу на течении. Равномерная проводка у дна с паузами в закоряженных местах стабильно приносит щуку и судака там, где джиг цепляет траву. Колебалка с узким телом и медленной игрой — мой фаворит для глубины.
:::""",
    "warning": """:::warning
**Частая ошибка.** Вести колебалку слишком быстро и равномерно, как вертушку. Колеблющаяся блесна должна идти медленно, с заметными паузами, чиркая по дну и поднимая муть. Быстрая проводка заставляет её выходить наверх и теряет глубину, где держится хищник.
:::""",
    "myth": """:::myth
**Миф и правда.** Миф: чем крупнее колебалка, тем больше рыба. Правда: размер подбирается под активность хищника и кормовую базу. Крупная колебалка 25-30 г при вялом клёве отпугнёт окуня и некрупную щуку. Начните со средней — 10-15 г, и подстраивайтесь.
:::""",
    "secret": """:::secret
**Секрет.** Рабочая зона колебалки — 10-15 см от дна. Чтобы держать её в этом горизонте, делайте равномерную проводку с короткими паузами и лёгкими подёргиваниями кончиком удилища. Блесна должна идти, слегка касаясь дна и поднимая лёгкую муть — это провоцирует хищника.
:::""",
    "tip": """:::tip
**Совет.** В зарослях и коряжнике используйте колебалки с офсетным крючком или «незацепляйки». Проводка — медленное волочение по дну с короткими рывками. Колеблющаяся блесна с одинарным крючком, прижатым к телу, проходит сквозь траву без зацепов.
:::""",
}

# Находим и заменяем блоки по порядку (типы уникальны в этой статье)
for typ in ["summary","experience","warning","myth","secret","tip"]:
    # Найдём блок :::typ ... :::
    m = re.search(r"(^:::(" + typ + r")\n.*?^:::)", txt, re.S|re.M)
    if m:
        txt = txt[:m.start()] + new_calls[typ] + txt[m.end():]

open(p, "w", encoding="utf-8").write(txt)
print("Koleblyuschiesya: чужие callout заменены")
# Проверка
for m in re.finditer(r"^:::(\w+)", txt, re.M):
    print(" :::", m.group(1))
