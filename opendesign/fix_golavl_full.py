#!/usr/bin/env python3
"""golavl: удаляет чужой блок про спиннинг и ставит релевантный FAQ по голавлю."""
import re
p = "/Users/igor/project/fish-zone/content/lovit-golavlya-spinning-taktika-primanki.md"
txt = open(p, encoding="utf-8").read()

# Найти начало чужого блока: последний родной раздел — "Итог и практические рекомендации"
# Чужой блок начинается с текста про тест после Итога
marker = "Тест показывает"
idx = txt.find(marker)

# Найти начало контекста перед маркером (после последнего абзаца Итога)
if idx != -1:
    # Обрезаем всё после начала чужого блока, но сначала найдём границу — начало строки
    line_start = txt.rfind("\n", 0, idx) + 1
    # Сохраняем всё до начала чужого блока
    head = txt[:line_start].rstrip() + "\n"
    
    # Добавляем релевантный FAQ по голавлю
    faq = """\n## FAQ\n\n:::faq **На что ловить голавля в июне?**\nВ июне голавль активно кормится после нереста. Работают вращающиеся блёсны 1-2 номера с красной точкой, мелкие воблеры-минноу и попперы по утренним зорям. Держитесь перекатов и границ струи.\n:::\n\n:::faq **Какая блесна лучше всего ловит голавля?**\nКлассика — вращающаяся блесна с лепестком «комета» или «аглия», размер 1-3. Голавль реагирует на яркие точки: красный кембрик, опушку, муху на крючке. В чистой воде предпочитает натуральные тона.\n:::\n\n:::faq **Где искать голавля на реке?**\nГолавль держится на перекатах, под нависшими деревьями, у входа в омуты и на границе быстрой и тихой воды. Летом выходит на утреннюю и вечернюю зорю на поверхность за насекомыми.\n:::\n\n:::faq **Можно ли ловить голавля на силикон?**\nДа, особенно летом в траве и на заросших участках. Работают мелкие твистеры 2-3 см и черви на лёгкой джиг-головке. Но чаще голавль берёт именно на вращающуюся блесну и воблер.\n:::\n"""
    open(p, "w", encoding="utf-8").write(head + faq)
    print(f"golavl: чужой блок удалён, добавлен релевантный FAQ. Размер {len(head+faq)}")
else:
    print("golavl: маркер не найден")
