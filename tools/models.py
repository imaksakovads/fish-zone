from pydantic import BaseModel, Field


# ═══════════════════════════════════════════════════════════════════
# API модели (Pydantic — валидация на входе)
# ═══════════════════════════════════════════════════════════════════

class HumanizeRequest(BaseModel):
    """Входной запрос на обработку текста."""
    content: str = Field(..., min_length=1, description="Текст для очистки и переписывания")
    provider: Optional[str] = Field(default=None, description="Явный выбор провайдера: deepseek | gemini | local")
    max_tokens: int = Field(default=1024, ge=64, le=4096, description="Макс. токенов на ответ")


class HumanizeResponse(BaseModel):
    """Финальный ответ после обработки (используется, когда стриминг отключён)."""
    text: str = Field(default="", description="Обработанный текст")
    provider_used: str = Field(default="", description="Провайдер, который сгенерировал ответ")
    duration_ms: float = Field(default=0.0, description="Время генерации в миллисекундах")
    error: Optional[str] = Field(default=None, description="Текст ошибки, если не удалось")


# ═══════════════════════════════════════════════════════════════════
# Внутренние структуры (dataclass — без Pydantic overhead)
# ═══════════════════════════════════════════════════════════════════

@dataclass
class ProviderConfig:
    """Настройки одного API-провайдера."""
    name: str
    api_url: str
    model: str
    api_key: str = ""
    connect_timeout: float = 5.0
    read_timeout: float = 60.0
    max_retries: int = 2


@dataclass
class Chunk:
    """Фрагмент текста после разбиения."""
    index: int
    text: str
    char_count: int
    token_estimate: int


@dataclass
class ProviderResult:
    """Результат вызова одного провайдера (для одного чанка)."""
    text: str
    provider_used: str
    duration_ms: float
    error: Optional[str] = None


