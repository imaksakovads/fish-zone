"""
Типизированные модели для Robust Humanizer.

Включает:
  - Request / Response — API-контракты
  - ProviderConfig — настройки провайдера (endpoint, модель, ключ)
  - Chunk — единица текста после разбиения
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field

from dotenv import load_dotenv
load_dotenv()  # Загружаем .env ДО того, как DEFAULT_PROVIDERS прочитает os.getenv()
